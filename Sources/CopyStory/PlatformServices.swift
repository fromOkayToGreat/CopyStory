enum PlatformServiceError: LocalizedError {
    case clipboardWrite, emptyPayload, hotKey(OSStatus), invalidShortcut

    var errorDescription: String? {
        switch self {
        case .clipboardWrite: return "CopyStory could not write this item to the clipboard."
        case .emptyPayload: return "This item no longer has usable content."
        case .hotKey(let status): return "This shortcut could not be registered (macOS error \(status)). Choose another shortcut."
        case .invalidShortcut: return "Choose a key together with Command, Control, or Option."
        }
    }
}

/// Foreground identity is best-effort attribution, not an authenticated producer.
struct ClipboardSource {
    let name: String?
    let bundleID: String?

    @MainActor static func frontmost() -> ClipboardSource {
        let app = NSWorkspace.shared.frontmostApplication
        guard app?.processIdentifier != ProcessInfo.processInfo.processIdentifier else {
            return ClipboardSource(name: nil, bundleID: nil)
        }
        return ClipboardSource(name: app?.localizedName, bundleID: app?.bundleIdentifier)
    }
}

@MainActor
final class ClipboardMonitor {
    var isPaused = false {
        didSet {
            guard oldValue != isPaused else { return }
            discardPendingCapture()
            reportState()
        }
    }
    var respectConfidential = true
    var excludedBundleIDs: Set<String> = [] {
        didSet { if excludedBundleIDs != oldValue { discardPendingCapture() } }
    }
    private(set) var isLocked = false

    private let pasteboard: NSPasteboard
    private let onCapture: (CapturePayload) -> Void
    private let onStatus: (String?) -> Void
    private let normalizeImage: @Sendable (Data) -> Result<ImageNormalizer.Normalized, ImageNormalizationError>
    private let sourceApplication: @MainActor () -> ClipboardSource
    private var timer: Timer?
    private var lastChangeCount = 0
    private var lastOwnWriteCount: Int?
    private var generation = 0
    private(set) var isDecoding = false
    private var observers: [(NotificationCenter, NSObjectProtocol)] = []
    private var lastStatus: String?
    private var deliveredStatus = false
    private var attemptedPermissionPrompt = false
    private static let ownMarker = NSPasteboard.PasteboardType("app.copystory.own-write")
    private static let sourceMarker = NSPasteboard.PasteboardType("org.nspasteboard.source")
    private static let alwaysSkipped: Set<String> = [
        "org.nspasteboard.TransientType", "org.nspasteboard.AutoGeneratedType",
        "de.petermaurer.TransientPasteboardType", "com.typeit4me.clipping",
        "app.copystory.own-write"
    ]
    private static let confidential: Set<String> = [
        "org.nspasteboard.ConcealedType", "org.nspasteboard.ConfidentialType",
        "com.agilebits.onepassword", "com.apple.is-confidential"
    ]
    private static let imageTypes: [NSPasteboard.PasteboardType] = [
        .png, .tiff, .init(UTType.jpeg.identifier), .init(UTType.heic.identifier),
        .init(UTType.gif.identifier), .init(UTType.bmp.identifier), .init("org.webmproject.webp")
    ]
    static let maximumTextBytes = 32_000_000
    static let maximumImageBytes = 100_000_000

    var hasCurrentOwnWrite: Bool {
        lastOwnWriteCount == pasteboard.changeCount
    }

    init(onCapture: @escaping (CapturePayload) -> Void,
         onStatus: @escaping (String?) -> Void,
         pasteboard: NSPasteboard = .general,
         sourceApplication: @escaping @MainActor () -> ClipboardSource = { ClipboardSource.frontmost() },
         normalizeImage: @escaping @Sendable (Data) -> Result<ImageNormalizer.Normalized, ImageNormalizationError> = { ImageNormalizer.normalize($0) }) {
        self.onCapture = onCapture
        self.onStatus = onStatus
        self.pasteboard = pasteboard
        self.normalizeImage = normalizeImage
        self.sourceApplication = sourceApplication
    }

    func start() {
        guard timer == nil else { return }
        // Do not save the clipboard present before launch, pause, or unlock.
        lastChangeCount = pasteboard.changeCount
        isLocked = Self.sessionIsUnavailable
        observeLocks()
        let timer = Timer(timeInterval: 0.5, repeats: true) { [weak self] _ in
            MainActor.assumeIsolated { self?.poll() }
        }
        timer.tolerance = 0.05
        RunLoop.main.add(timer, forMode: .common)
        self.timer = timer
        reportState()
    }

    func stop() {
        timer?.invalidate()
        timer = nil
        for (center, observer) in observers { center.removeObserver(observer) }
        observers.removeAll()
        discardPendingCapture()
    }

    /// Called only by an explicit history copy/paste action.
    func write(_ payload: CapturePayload) throws {
        let item = NSPasteboardItem()
        var hasContent = false
        if let image = payload.imageData, !image.isEmpty {
            guard image.count <= Self.maximumImageBytes else { throw PlatformServiceError.emptyPayload }
            hasContent = item.setData(image, forType: .png)
        }
        if let text = payload.text, !text.isEmpty {
            guard text.utf8.count <= Self.maximumTextBytes else { throw PlatformServiceError.emptyPayload }
            let wroteText = item.setString(text, forType: .string)
            hasContent = wroteText || hasContent
        }
        guard hasContent else { throw PlatformServiceError.emptyPayload }
        item.setData(Data(), forType: Self.ownMarker)
        item.setString(Bundle.main.bundleIdentifier ?? "app.copystory", forType: Self.sourceMarker)
        // Universal Clipboard is explicitly disabled for writes made by this local-only app.
        pasteboard.prepareForNewContents(with: .currentHostOnly)
        let succeeded = pasteboard.writeObjects([item])
        lastChangeCount = pasteboard.changeCount
        lastOwnWriteCount = succeeded ? lastChangeCount : nil
        if !succeeded { throw PlatformServiceError.clipboardWrite }
    }

    static func openClipboardSettings() {
        if let url = URL(string: "x-apple.systempreferences:com.apple.settings.PrivacySecurity.extension") {
            NSWorkspace.shared.open(url)
        }
    }

    /// Invalidates in-flight work without changing the clipboard or recording state.
    func discardPendingCapture() {
        generation += 1
        lastChangeCount = pasteboard.changeCount
    }

    private func setLocked(_ locked: Bool) {
        guard isLocked != locked else { return }
        isLocked = locked
        discardPendingCapture()
        reportState()
    }

    // macOS has no public lock-state notification constant. Combine the system's
    // distributed screen-lock notifications with public session/sleep events and
    // a session snapshot, including a conservative locked-at-launch check.
    private static var sessionIsUnavailable: Bool {
        guard let session = CGSessionCopyCurrentDictionary() as? [String: Any] else { return true }
        if (session["CGSSessionScreenIsLocked"] as? Bool) == true { return true }
        if (session[kCGSessionOnConsoleKey as String] as? Bool) == false { return true }
        if (session[kCGSessionLoginDoneKey as String] as? Bool) == false { return true }
        return false
    }

    private func observeLocks() {
        let distributed = DistributedNotificationCenter.default()
        observe(distributed, name: .init("com.apple.screenIsLocked")) { $0.setLocked(true) }
        observe(distributed, name: .init("com.apple.screenIsUnlocked")) { $0.setLocked(Self.sessionIsUnavailable) }
        let workspace = NSWorkspace.shared.notificationCenter
        observe(workspace, name: NSWorkspace.sessionDidResignActiveNotification) { $0.setLocked(true) }
        observe(workspace, name: NSWorkspace.willSleepNotification) { $0.setLocked(true) }
        observe(workspace, name: NSWorkspace.screensDidSleepNotification) { $0.setLocked(true) }
        observe(workspace, name: NSWorkspace.sessionDidBecomeActiveNotification) { $0.setLocked(Self.sessionIsUnavailable) }
        observe(workspace, name: NSWorkspace.didWakeNotification) { $0.setLocked(Self.sessionIsUnavailable) }
        observe(workspace, name: NSWorkspace.screensDidWakeNotification) { $0.setLocked(Self.sessionIsUnavailable) }
    }

    private func observe(_ center: NotificationCenter, name: Notification.Name,
                         action: @escaping (ClipboardMonitor) -> Void) {
        let token = center.addObserver(forName: name, object: nil, queue: .main) { [weak self] _ in
            MainActor.assumeIsolated { if let self { action(self) } }
        }
        observers.append((center, token))
    }

    private func report(_ message: String?) {
        if !deliveredStatus || message != lastStatus {
            deliveredStatus = true
            lastStatus = message
            onStatus(message)
        }
    }

    private func reportState() {
        if isLocked { report("Recording paused while the Mac is locked or asleep.") }
        else if isPaused { report("Recording paused.") }
        else if pasteboard.accessBehavior == .alwaysDeny {
            report("Clipboard access is denied. Allow CopyStory in System Settings → Privacy & Security → Paste from Other Apps.")
        } else if pasteboard.accessBehavior == .ask && attemptedPermissionPrompt {
            report("For continuous recording, allow CopyStory to paste from other apps in System Settings → Privacy & Security.")
        } else { report(nil) }
    }

    /// Internal for named-pasteboard verification; never polls before start().
    func poll() {
        guard timer != nil else { return }
        if Self.sessionIsUnavailable { setLocked(true) }
        guard !isLocked, !isPaused else {
            lastChangeCount = pasteboard.changeCount
            return
        }
        guard !isDecoding else { return }
        let count = pasteboard.changeCount
        guard count != lastChangeCount else { reportState(); return }
        lastChangeCount = count
        let behavior = pasteboard.accessBehavior
        guard behavior != .alwaysDeny else { reportState(); return }
        // Give macOS one opportunity to present its initial permission prompt.
        // Afterwards, never prompt again for each background polling interval.
        if behavior == .ask && attemptedPermissionPrompt { reportState(); return }
        if behavior == .default || behavior == .ask { attemptedPermissionPrompt = true }
        let captureGeneration = generation
        let types = Set((pasteboard.types ?? []).map(\.rawValue))
        guard types.isDisjoint(with: Self.alwaysSkipped),
              !respectConfidential || types.isDisjoint(with: Self.confidential) else { return }
        let source = sourceApplication()
        if let bundleID = source.bundleID, excludedBundleIDs.contains(bundleID) { return }
        let capturedAt = Date()
        let text = pasteboard.string(forType: .string)
        if let text, text.utf8.count > Self.maximumTextBytes {
            report("Skipped a text item larger than the 32 MB capture safety limit.")
            return
        }
        var imageData: Data?
        for type in Self.imageTypes where types.contains(type.rawValue) {
            if let data = pasteboard.data(forType: type), !data.isEmpty {
                guard data.count <= Self.maximumImageBytes else {
                    report("Skipped an image larger than the 100 MB capture safety limit.")
                    return
                }
                imageData = data
                break
            }
        }
        // A producer can change the clipboard while fulfilling promised data.
        // Never combine representations from two different clipboard events.
        guard pasteboard.changeCount == count, generation == captureGeneration, !isPaused, !isLocked else { return }
        guard !Self.sessionIsUnavailable else { setLocked(true); return }
        let sourceApp = source.name
        let sourceBundle = source.bundleID
        let usableText = text.flatMap { $0.isEmpty ? nil : $0 }
        guard let imageData else {
            guard let usableText else { reportState(); return }
            onCapture(CapturePayload(text: usableText, imageData: nil, thumbnailData: nil,
                                     pixelWidth: nil, pixelHeight: nil, sourceApp: sourceApp,
                                     sourceBundleID: sourceBundle, capturedAt: capturedAt))
            reportState()
            return
        }
        isDecoding = true
        let normalizeImage = self.normalizeImage
        Task { [weak self] in
            let result = await Task.detached(priority: .utility) {
                normalizeImage(imageData)
            }.value
            guard let self else { return }
            self.isDecoding = false
            guard self.generation == captureGeneration, self.timer != nil,
                  !self.isPaused, !self.isLocked, !Self.sessionIsUnavailable else { return }
            switch result {
            case .success(let image):
                self.onCapture(CapturePayload(text: usableText, imageData: image.png, thumbnailData: image.thumbnail,
                                              pixelWidth: image.width, pixelHeight: image.height,
                                              sourceApp: sourceApp, sourceBundleID: sourceBundle, capturedAt: capturedAt))
                self.reportState()
            case .failure:
                self.report("Skipped an unreadable image or one exceeding the 32-megapixel / 16,384-pixel capture safety limits.")
            }
        }
    }
}

enum ImageNormalizationError: Error { case invalidOrTooLarge }

enum ImageNormalizer {
    struct Normalized: Sendable {
        let png: Data
        let thumbnail: Data
        let width: Int
        let height: Int
    }

    /// ImageIO reads header dimensions before decoding. Only the first frame is
    /// captured. Transform applies EXIF orientation and PNG preserves alpha.
    static func normalize(_ data: Data) -> Result<Normalized, ImageNormalizationError> {
        autoreleasepool {
            guard !data.isEmpty, data.count <= 100_000_000,
                  let source = CGImageSourceCreateWithData(data as CFData, [kCGImageSourceShouldCache: false] as CFDictionary),
                  CGImageSourceGetCount(source) > 0,
                  let properties = CGImageSourceCopyPropertiesAtIndex(source, 0, nil) as? [CFString: Any],
                  let width = (properties[kCGImagePropertyPixelWidth] as? NSNumber)?.intValue,
                  let height = (properties[kCGImagePropertyPixelHeight] as? NSNumber)?.intValue,
                  width > 0, height > 0, width <= 16_384, height <= 16_384,
                  Int64(width) * Int64(height) <= 32_000_000 else { return .failure(.invalidOrTooLarge) }
            let options: [CFString: Any] = [
                kCGImageSourceCreateThumbnailFromImageAlways: true,
                kCGImageSourceCreateThumbnailWithTransform: true,
                kCGImageSourceThumbnailMaxPixelSize: max(width, height),
                kCGImageSourceShouldCacheImmediately: true
            ]
            guard let image = CGImageSourceCreateThumbnailAtIndex(source, 0, options as CFDictionary),
                  image.width > 0, image.height > 0,
                  image.width <= 16_384, image.height <= 16_384,
                  Int64(image.width) * Int64(image.height) <= 32_000_000,
                  let png = encodePNG(image), png.count <= 100_000_000 else { return .failure(.invalidOrTooLarge) }
            let smallOptions: [CFString: Any] = [
                kCGImageSourceCreateThumbnailFromImageAlways: true,
                kCGImageSourceCreateThumbnailWithTransform: true,
                kCGImageSourceThumbnailMaxPixelSize: 320,
                kCGImageSourceShouldCacheImmediately: true
            ]
            guard let thumbnail = CGImageSourceCreateThumbnailAtIndex(source, 0, smallOptions as CFDictionary),
                  let thumbnailData = encodePNG(thumbnail), thumbnailData.count <= 1_000_000 else { return .failure(.invalidOrTooLarge) }
            return .success(Normalized(png: png, thumbnail: thumbnailData, width: image.width, height: image.height))
        }
    }

    private static func encodePNG(_ image: CGImage) -> Data? {
        let data = NSMutableData()
        guard let destination = CGImageDestinationCreateWithData(data, UTType.png.identifier as CFString, 1, nil) else { return nil }
        CGImageDestinationAddImage(destination, image, nil)
        guard CGImageDestinationFinalize(destination) else { return nil }
        return data as Data
    }
}

@MainActor
final class GlobalHotKey {
    private var hotKey: EventHotKeyRef?
    private var handler: EventHandlerRef?
    private var currentKey: UInt32?
    private var currentModifiers: UInt32?
    private let onTrigger: () -> Void
    private let signature: OSType = 0x43505354 // CPST

    init(onTrigger: @escaping () -> Void) { self.onTrigger = onTrigger }

    deinit {
        if let hotKey { UnregisterEventHotKey(hotKey) }
        if let handler { RemoveEventHandler(handler) }
    }

    func register(keyCode: UInt32, modifiers: UInt32) throws {
        if currentKey == keyCode, currentModifiers == modifiers, hotKey != nil { return }
        guard keyCode <= 127, modifiers & UInt32(cmdKey | controlKey | optionKey) != 0 else {
            throw PlatformServiceError.invalidShortcut
        }
        if handler == nil {
            var specification = EventTypeSpec(eventClass: OSType(kEventClassKeyboard), eventKind: UInt32(kEventHotKeyPressed))
            let status = InstallEventHandler(GetApplicationEventTarget(), { _, event, context in
                guard let event, let context else { return OSStatus(eventNotHandledErr) }
                var identifier = EventHotKeyID()
                let result = GetEventParameter(event, EventParamName(kEventParamDirectObject), EventParamType(typeEventHotKeyID),
                                               nil, MemoryLayout<EventHotKeyID>.size, nil, &identifier)
                guard result == noErr else { return result }
                return MainActor.assumeIsolated {
                    let owner = Unmanaged<GlobalHotKey>.fromOpaque(context).takeUnretainedValue()
                    guard identifier.signature == owner.signature, identifier.id == 1 else { return OSStatus(eventNotHandledErr) }
                    owner.onTrigger()
                    return noErr
                }
            }, 1, &specification, Unmanaged.passUnretained(self).toOpaque(), &handler)
            guard status == noErr else { throw PlatformServiceError.hotKey(status) }
        }
        var replacement: EventHotKeyRef?
        let identifier = EventHotKeyID(signature: signature, id: 1)
        let result = RegisterEventHotKey(keyCode, modifiers, identifier, GetApplicationEventTarget(), UInt32(kEventHotKeyExclusive), &replacement)
        guard result == noErr else { throw PlatformServiceError.hotKey(result) }
        if let hotKey { UnregisterEventHotKey(hotKey) }
        hotKey = replacement
        currentKey = keyCode
        currentModifiers = modifiers
    }

    func unregister() {
        if let hotKey { UnregisterEventHotKey(hotKey) }
        if let handler { RemoveEventHandler(handler) }
        hotKey = nil
        handler = nil
        currentKey = nil
        currentModifiers = nil
    }
}

@MainActor
struct PasteTarget {
    let window: AXUIElement
    let element: AXUIElement

    func matches(window: AXUIElement?, element: AXUIElement?) -> Bool {
        guard let window, let element else { return false }
        return CFEqual(self.window, window) && CFEqual(self.element, element)
    }
}

@MainActor
final class PasteCoordinator {
    private(set) var isPasting = false
    private var destinationApp: NSRunningApplication?
    private var destinationTarget: PasteTarget?
    private var lastExternalApp: NSRunningApplication?
    private var activationObserver: NSObjectProtocol?

    init() {
        lastExternalApp = NSWorkspace.shared.frontmostApplication
        activationObserver = NSWorkspace.shared.notificationCenter.addObserver(
            forName: NSWorkspace.didActivateApplicationNotification, object: nil, queue: .main
        ) { [weak self] notification in
            MainActor.assumeIsolated {
                guard let app = notification.userInfo?[NSWorkspace.applicationUserInfoKey] as? NSRunningApplication,
                      app.processIdentifier != ProcessInfo.processInfo.processIdentifier else { return }
                self?.lastExternalApp = app
            }
        }
    }

    static var accessibilityGranted: Bool { AXIsProcessTrusted() }

    static func requestAccessibility() {
        let options = [kAXTrustedCheckOptionPrompt.takeUnretainedValue() as String: true] as CFDictionary
        _ = AXIsProcessTrustedWithOptions(options)
    }

    static func openAccessibilitySettings() {
        if let url = URL(string: "x-apple.systempreferences:com.apple.preference.security?Privacy_Accessibility") {
            NSWorkspace.shared.open(url)
        }
    }

    func rememberDestination() {
        guard !isPasting else { return }
        let frontmost = NSWorkspace.shared.frontmostApplication
        let ownPID = ProcessInfo.processInfo.processIdentifier
        let app = frontmost?.processIdentifier == ownPID ? lastExternalApp : frontmost
        guard let app, app.processIdentifier != ownPID, !app.isTerminated else {
            destinationApp = nil
            destinationTarget = nil
            return
        }
        destinationApp = app
        destinationTarget = nil
        if Self.accessibilityGranted,
           let window = Self.focusedWindow(pid: app.processIdentifier),
           let element = Self.focusedElement(pid: app.processIdentifier) {
            destinationTarget = PasteTarget(window: window, element: element)
        }
    }

    func paste(using monitor: ClipboardMonitor, payload: CapturePayload, closePanel: () -> Void) async -> String {
        guard !isPasting else { return "A paste request is already in progress." }
        isPasting = true
        defer { isPasting = false }
        do { try monitor.write(payload) }
        catch { return error.localizedDescription }
        let app = destinationApp
        let target = destinationTarget
        closePanel()
        guard Self.accessibilityGranted else {
            return "Copied. Enable Accessibility for direct paste, or press ⌘V in your app."
        }
        guard let app, !app.isTerminated, app.processIdentifier != ProcessInfo.processInfo.processIdentifier else {
            return "Copied. The previous app is unavailable; paste manually with ⌘V."
        }
        guard let target else {
            return "Copied. Could not identify the original window and field; paste manually with ⌘V."
        }
        let pid = app.processIdentifier
        guard app.activate(options: []) else {
            return "Copied. Could not activate the previous app; paste manually with ⌘V."
        }
        for _ in 0..<30 {
            guard !Task.isCancelled, !app.isTerminated else { return "Copied. Paste was cancelled; paste manually with ⌘V." }
            if NSWorkspace.shared.frontmostApplication?.processIdentifier == pid { break }
            try? await Task.sleep(nanoseconds: 30_000_000)
        }
        guard NSWorkspace.shared.frontmostApplication?.processIdentifier == pid else {
            return "Copied. The previous app did not become active; paste manually with ⌘V."
        }
        let window = target.window
        do {
            AXUIElementSetMessagingTimeout(window, 0.2)
            _ = AXUIElementPerformAction(window, kAXRaiseAction as CFString)
            _ = AXUIElementSetAttributeValue(window, kAXMainAttribute as CFString, kCFBooleanTrue)
            let appElement = AXUIElementCreateApplication(pid)
            AXUIElementSetMessagingTimeout(appElement, 0.2)
            _ = AXUIElementSetAttributeValue(appElement, kAXFocusedWindowAttribute as CFString, window)
        }
        // Give window activation a single bounded settling interval; never retry paste.
        try? await Task.sleep(nanoseconds: 80_000_000)
        guard !Task.isCancelled, !app.isTerminated, Self.accessibilityGranted,
              NSWorkspace.shared.frontmostApplication?.processIdentifier == pid else {
            return "Copied. Focus changed before pasting; paste manually with ⌘V."
        }
        guard target.matches(window: Self.focusedWindow(pid: pid), element: Self.focusedElement(pid: pid)) else {
            return "Copied. The original window or field changed; paste manually with ⌘V."
        }
        guard let source = CGEventSource(stateID: .privateState),
              let down = CGEvent(keyboardEventSource: source, virtualKey: CGKeyCode(kVK_ANSI_V), keyDown: true),
              let up = CGEvent(keyboardEventSource: source, virtualKey: CGKeyCode(kVK_ANSI_V), keyDown: false) else {
            return "Copied. Could not request paste; paste manually with ⌘V."
        }
        down.flags = .maskCommand
        up.flags = .maskCommand
        down.setIntegerValueField(.keyboardEventAutorepeat, value: 0)
        guard NSWorkspace.shared.frontmostApplication?.processIdentifier == pid, !app.isTerminated else {
            return "Copied. Focus changed before pasting; paste manually with ⌘V."
        }
        guard monitor.hasCurrentOwnWrite else {
            return "The clipboard changed before paste was requested. Choose the history item again."
        }
        guard target.matches(window: Self.focusedWindow(pid: pid), element: Self.focusedElement(pid: pid)),
              Self.accessibilityGranted,
              NSWorkspace.shared.frontmostApplication?.processIdentifier == pid,
              !app.isTerminated, monitor.hasCurrentOwnWrite else {
            return "Copied. The paste destination changed; paste manually with ⌘V."
        }
        // Route this single pair to the verified process, never to a newly active app.
        down.postToPid(pid)
        up.postToPid(pid)
        return "Paste requested in \(app.localizedName ?? "the previous app"). The item remains copied."
    }

    private static func focusedWindow(pid: pid_t) -> AXUIElement? {
        focusedAttribute(pid: pid, attribute: kAXFocusedWindowAttribute)
    }

    private static func focusedElement(pid: pid_t) -> AXUIElement? {
        focusedAttribute(pid: pid, attribute: kAXFocusedUIElementAttribute)
    }

    private static func focusedAttribute(pid: pid_t, attribute: String) -> AXUIElement? {
        let app = AXUIElementCreateApplication(pid)
        AXUIElementSetMessagingTimeout(app, 0.2)
        var value: CFTypeRef?
        guard AXUIElementCopyAttributeValue(app, attribute as CFString, &value) == .success,
              let value, CFGetTypeID(value) == AXUIElementGetTypeID() else { return nil }
        return (value as! AXUIElement)
    }
}

@MainActor
enum LoginService {
    static var isEnabled: Bool { SMAppService.mainApp.status == .enabled }

    static var isRegistered: Bool {
        let status = SMAppService.mainApp.status
        return status == .enabled || status == .requiresApproval
    }

    static var statusText: String {
        switch SMAppService.mainApp.status {
        case .enabled: return "Enabled — CopyStory can launch at login."
        case .notRegistered: return "Disabled — CopyStory is not registered to launch at login."
        case .requiresApproval: return "Approval required in System Settings → General → Login Items & Extensions."
        case .notFound: return "Unavailable — keep the signed CopyStory app in Applications and try again."
        @unknown default: return "Login status is unavailable. Check System Settings."
        }
    }

    static func setEnabled(_ enabled: Bool) throws {
        let service = SMAppService.mainApp
        if enabled {
            if service.status == .enabled || service.status == .requiresApproval { return }
            try service.register()
        } else if service.status != .notRegistered {
            try service.unregister()
        }
    }

    static func openSettings() { SMAppService.openSystemSettingsLoginItems() }
}
