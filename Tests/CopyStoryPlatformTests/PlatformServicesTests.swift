@Suite(.serialized)
struct PlatformServicesTests {
    @MainActor
    @Test func testCaptureBaselineUnicodeMarkersPauseAndOwnWrites() throws {
        let board = NSPasteboard.withUniqueName()
        defer { board.releaseGlobally() }
        var captures: [CapturePayload] = []
        let monitor = ClipboardMonitor(onCapture: { captures.append($0) }, onStatus: { _ in }, pasteboard: board)
        try writeSynthetic("pre-launch synthetic content", to: board)
        monitor.start()
        defer { monitor.stop() }
        try #require(!monitor.isLocked, "An active, unlocked macOS session is required for pasteboard capture tests.")
        monitor.poll()
        #expect(captures.isEmpty, "Startup must baseline, not capture existing content.")

        let text = "  Unicode 👩🏽‍💻 café 日本語\n\tgit status\n  "
        try writeSynthetic(text, to: board)
        monitor.poll()
        #expect(captures.count == 1)
        #expect(captures.last?.text == text)

        for marker in ["org.nspasteboard.ConcealedType", "org.nspasteboard.TransientType", "org.nspasteboard.AutoGeneratedType"] {
            try writeSynthetic("synthetic marker fixture", to: board, marker: marker)
            monitor.poll()
            #expect(captures.count == 1, "Must skip \(marker).")
        }
        monitor.isPaused = true
        try writeSynthetic("synthetic paused content", to: board)
        monitor.poll()
        monitor.isPaused = false
        monitor.poll()
        #expect(captures.count == 1, "Resuming must baseline instead of recording paused content.")

        let first = try #require(captures.first)
        try monitor.write(first)
        monitor.poll()
        #expect(captures.count == 1)
        #expect(monitor.hasCurrentOwnWrite)
        try writeSynthetic("synthetic subsequent copy", to: board)
        #expect(!(monitor.hasCurrentOwnWrite), "An intervening copy must cancel a pending direct paste.")
        monitor.poll()
        #expect(captures.count == 2)
    }

    @MainActor
    @Test func testConfidentialPreferenceDoesNotDisableTransientProtection() throws {
        let board = NSPasteboard.withUniqueName()
        defer { board.releaseGlobally() }
        var captures: [CapturePayload] = []
        let monitor = ClipboardMonitor(onCapture: { captures.append($0) }, onStatus: { _ in }, pasteboard: board)
        monitor.start()
        defer { monitor.stop() }
        try #require(!monitor.isLocked, "An active, unlocked macOS session is required.")
        monitor.respectConfidential = false
        try writeSynthetic("synthetic confidential fixture", to: board, marker: "org.nspasteboard.ConcealedType")
        monitor.poll()
        #expect(captures.count == 1)
        try writeSynthetic("synthetic transient fixture", to: board, marker: "org.nspasteboard.TransientType")
        monitor.poll()
        #expect(captures.count == 1)
    }

    @Test func testImageNormalizationPreservesDimensionsAndTransparency() throws {
        let original = try makePNG(width: 20, height: 10)
        let normalized = try ImageNormalizer.normalize(original).get()
        #expect(normalized.width == 20)
        #expect(normalized.height == 10)
        let source = try #require(CGImageSourceCreateWithData(normalized.png as CFData, nil))
        let image = try #require(CGImageSourceCreateImageAtIndex(source, 0, nil))
        let rendered = try #require(CGContext(data: nil, width: 20, height: 10, bitsPerComponent: 8,
                                              bytesPerRow: 80, space: CGColorSpaceCreateDeviceRGB(),
                                              bitmapInfo: CGImageAlphaInfo.premultipliedLast.rawValue))
        rendered.draw(image, in: CGRect(x: 0, y: 0, width: 20, height: 10))
        let pixels = try #require(rendered.data).assumingMemoryBound(to: UInt8.self)
        #expect((126...129).contains(pixels[3]), "The source's half-opacity must survive PNG normalization.")
        let thumbnailSource = try #require(CGImageSourceCreateWithData(normalized.thumbnail as CFData, nil))
        let thumbnail = try #require(CGImageSourceCreateImageAtIndex(thumbnailSource, 0, nil))
        #expect(max(thumbnail.width, thumbnail.height) <= 320)
        #expect(thumbnail.width * image.height == thumbnail.height * image.width)
    }

    @Test func testMalformedAndOversizedImagesAreRejected() throws {
        #expect(throws: (any Error).self) { try ImageNormalizer.normalize(Data([0, 1, 2, 3])).get() }
        // Only 65 KB of decoded pixels, yet wider than the permitted dimension.
        let tooWide = try makePNG(width: 16_385, height: 1)
        #expect(throws: (any Error).self) { try ImageNormalizer.normalize(tooWide).get() }
        #expect(throws: (any Error).self) { try ImageNormalizer.normalize(Data()).get() }
    }

    @MainActor
    @Test func testImageAndAssociatedTextProduceOneCapture() async throws {
        let board = NSPasteboard.withUniqueName()
        defer { board.releaseGlobally() }
        var captures: [CapturePayload] = []
        let monitor = ClipboardMonitor(onCapture: { captures.append($0) }, onStatus: { _ in }, pasteboard: board)
        monitor.start()
        defer { monitor.stop() }
        try #require(!monitor.isLocked, "An active, unlocked macOS session is required.")
        let png = try makePNG(width: 20, height: 10)
        try writeSynthetic("synthetic associated text", to: board, image: png)
        monitor.poll()
        for _ in 0..<100 where captures.isEmpty { try await Task.sleep(nanoseconds: 20_000_000) }
        #expect(captures.count == 1)
        let item = try #require(captures.first)
        #expect(item.text == "synthetic associated text")
        #expect(item.imageData != nil)
        #expect(item.thumbnailData != nil)
        #expect(item.pixelWidth == 20)
        #expect(item.pixelHeight == 10)
    }

    // The compatibility coordinator is deliberately retired. Explicit Copy and
    // Paste use NativeRequestAdapter; this old entry must not become a second path.
    @Test func legacyPasteEntryHasNoWriteAdmissionOrCloseEffects() {
        var effects = 0
        let feedback = AutomaticPastePolicy.request(write: { effects += 1 },
            admit: { effects += 1 }, close: { effects += 1 })
        #expect(effects == 0)
        #expect(feedback.contains("Nothing was copied or sent"))
    }

    @MainActor
    @Test func testExclusiveHotKeyReportsConflictAndPreservesExistingRegistration() throws {
        let first = GlobalHotKey(onTrigger: {})
        let second = GlobalHotKey(onTrigger: {})
        defer { first.unregister(); second.unregister() }
        let modifiers = UInt32(cmdKey | controlKey | optionKey | shiftKey)
        try first.register(keyCode: UInt32(kVK_F20), modifiers: modifiers)
        // Reapplying one's own shortcut is idempotent. A second owner must fail.
        try first.register(keyCode: UInt32(kVK_F20), modifiers: modifiers)
        #expect(throws: (any Error).self) { try second.register(keyCode: UInt32(kVK_F20), modifiers: modifiers) }
        first.unregister()
        try second.register(keyCode: UInt32(kVK_F20), modifiers: modifiers)
        #expect(throws: (any Error).self) { try second.register(keyCode: UInt32(kVK_ANSI_A), modifiers: 0) }
    }

    @MainActor
    private func writeSynthetic(_ text: String, to board: NSPasteboard, marker: String? = nil, image: Data? = nil) throws {
        let item = NSPasteboardItem()
        #expect(item.setString(text, forType: .string))
        if let marker { #expect(item.setData(Data(), forType: .init(marker))) }
        if let image { #expect(item.setData(image, forType: .png)) }
        board.clearContents()
        try #require(board.writeObjects([item]), "Named pasteboard service is unavailable in this session.")
    }

    private func makePNG(width: Int, height: Int) throws -> Data {
        let context = try #require(CGContext(data: nil, width: width, height: height, bitsPerComponent: 8,
                                             bytesPerRow: width * 4, space: CGColorSpaceCreateDeviceRGB(),
                                             bitmapInfo: CGImageAlphaInfo.premultipliedLast.rawValue))
        context.setFillColor(CGColor(red: 0.5, green: 0.25, blue: 0.75, alpha: 0.5))
        context.fill(CGRect(x: 0, y: 0, width: width, height: height))
        let data = NSMutableData()
        let destination = try #require(CGImageDestinationCreateWithData(data, UTType.png.identifier as CFString, 1, nil))
        CGImageDestinationAddImage(destination, try #require(context.makeImage()), nil)
        #expect(CGImageDestinationFinalize(destination))
        return data as Data
    }
}
